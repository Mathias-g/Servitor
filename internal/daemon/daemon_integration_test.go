// TestDaemonSubmitAndManual drives the control-plane registration and manual
// trigger through a running daemon: submit a workflow, trigger it, and verify
// the worker executes the run.
func TestDaemonSubmitAndManual(t *testing.T) {
	ext := daemonExtPath(t)
	dbPath := filepath.Join(t.TempDir(), "d.db")

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	started := make(chan string, 1)
	done := make(chan error, 1)
	go func() {
		done <- Run(ctx, Config{
			Addr:         "127.0.0.1:0",
			DBPath:       dbPath,
			ExtPath:      ext,
			Workers:      1,
			DrainTimeout: 2 * time.Second,
			Started:      func(a string) { started <- a },
		})
	}()

	select {
	case cpAddr := <-started:
		ctl := protocol.NewClient(cpAddr)
		if err := ctl.Health(ctx); err != nil {
			t.Fatalf("health: %v", err)
		}
		if _, err := ctl.Submit(ctx, []byte(wfShellYAML)); err != nil {
			t.Fatalf("submit: %v", err)
		}
		if err := ctl.Trigger(ctx, "demo", []byte(`{"x":1}`)); err != nil {
			t.Fatalf("trigger: %v", err)
		}
	case <-time.After(5 * time.Second):
		t.Fatal("daemon did not start")
	}

	// Verify the worker executed the run by reading results from a second
	// handle to the same file.
	store, err := honker.Open(dbPath, ext)
	if err != nil {
		t.Fatalf("open test store: %v", err)
	}
	t.Cleanup(func() { _ = store.Close() })

	deadline := time.After(5 * time.Second)
	for {
		// The run id is generated by the daemon as <name>-<unixnano>; we cannot
		// predict it, so poll for any step result row.
		n, _ := store.StepResultCount()
		if n > 0 {
			break
		}
		select {
		case <-deadline:
			t.Fatal("worker did not execute the triggered run")
		case <-time.After(20 * time.Millisecond):
		}
	}

	cancel()
	select {
	case err := <-done:
		if err != nil {
			t.Fatalf("daemon shutdown error: %v", err)
		}
	case <-time.After(5 * time.Second):
		t.Fatal("daemon did not shut down")
	}
}

