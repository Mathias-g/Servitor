// TestDaemonWebhookReceiver verifies a signed Standard Webhooks request to the
// webhook listener enqueues a run.
func TestDaemonWebhookReceiver(t *testing.T) {
	ext := daemonExtPath(t)
	dbPath := filepath.Join(t.TempDir(), "d.db")
	whAddr := freePort(t)

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	started := make(chan string, 1)
	done := make(chan error, 1)
	go func() {
		done <- Run(ctx, Config{
			Addr:         "127.0.0.1:0",
			DBPath:       dbPath,
			ExtPath:      ext,
			WebhookAddr:  whAddr,
			Workers:      1,
			Secrets:      map[string]string{"WH_SECRET": "s3cret"},
			DrainTimeout: 2 * time.Second,
			Started:      func(a string) { started <- a },
		})
	}()

	select {
	case cpAddr := <-started:
		ctl := protocol.NewClient(cpAddr)
		if _, err := ctl.Submit(ctx, []byte(wfWebhookYAML)); err != nil {
			t.Fatalf("submit: %v", err)
		}
	case <-time.After(5 * time.Second):
		t.Fatal("daemon did not start")
	}

	// Send a signed webhook to the receiver.
	body := []byte(`{"event":"x"}`)
	ts := strconv.FormatInt(time.Now().Unix(), 10)
	id := "evt_1"
	mac := hmac.New(sha256.New, []byte("s3cret"))
	_, _ = mac.Write([]byte(id + "." + ts + "."))
	_, _ = mac.Write(body)
	sig := "v1," + base64.StdEncoding.EncodeToString(mac.Sum(nil))

	httpc := &http.Client{Timeout: 3 * time.Second}
	req, _ := http.NewRequestWithContext(ctx, http.MethodPost, "http://"+whAddr+"/hooks/demo", bytes.NewReader(body))
	req.Header.Set("webhook-id", id)
	req.Header.Set("webhook-timestamp", ts)
	req.Header.Set("webhook-signature", sig)
	resp, err := httpc.Do(req)
	if err != nil {
		t.Fatalf("webhook request: %v", err)
	}
	_ = resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("webhook status = %d, want 200", resp.StatusCode)
	}

	store, err := honker.Open(dbPath, ext)
	if err != nil {
		t.Fatalf("open test store: %v", err)
	}
	t.Cleanup(func() { _ = store.Close() })

	// Event was persisted.
	deadline := time.After(5 * time.Second)
	for {
		n, _ := store.EventCount()
		if n > 0 {
			break
		}
		select {
		case <-deadline:
			t.Fatal("event was not persisted")
		case <-time.After(20 * time.Millisecond):
		}
	}

	// The worker ran the workflow.
	runDeadline := time.After(5 * time.Second)
	for {
		n, _ := store.StepResultCount()
		if n > 0 {
			break
		}
		select {
		case <-runDeadline:
			t.Fatal("worker did not run the webhook-triggered workflow")
		case <-time.After(20 * time.Millisecond):
		}
	}

	cancel()
	select {
	case <-done:
	case <-time.After(5 * time.Second):
		t.Fatal("daemon did not shut down")
	}
}

